def screenshots(destination: Path = IMAGES) -> list[Path]:
    """Draw every scene in every language and theme; returns the files written."""
    destination.mkdir(parents=True, exist_ok=True)
    written = []
    themes = _themes()
    previous_home = os.environ.get("SESSIONBRIDGE_HOME")
    previous_check = os.environ.get("SESSIONBRIDGE_NO_UPDATE_CHECK")
    with tempfile.TemporaryDirectory() as home:
        os.environ["SESSIONBRIDGE_HOME"] = home
        os.environ["SESSIONBRIDGE_NO_UPDATE_CHECK"] = "1"
        import session_bridge.sync as sync

        saved_service = sync.SyncService
        sync.SyncService = lambda **kwargs: SimpleNamespace(list=_links)
        try:
            for lang in LANGUAGES:
                with _language(lang):
                    scenes = []
                    for run, keys, captures in _scenes(Path(home)):
                        with _capturing(keys) as recorder:
                            run()
                        scenes.append((recorder, captures))
                for recorder, captures in scenes:
                    for name, (prompt, history) in captures.items():
                        lines = recorder.frame(prompt, history=history)
                        for theme_name, theme in themes.items():
                            path = destination / f"{name}-{lang}-{theme_name}.svg"
                            svg = _svg(lines, name, lang, theme_name, theme)
                            path.write_text(svg, encoding="utf-8", newline="\n")
                            written.append(path)
        finally:
            sync.SyncService = saved_service
            _restore("SESSIONBRIDGE_HOME", previous_home)
            _restore("SESSIONBRIDGE_NO_UPDATE_CHECK", previous_check)
    return written


def _restore(name: str, value: str | None) -> None:
    if value is None:
        os.environ.pop(name, None)
    else:
        os.environ[name] = value


def _svg(lines, name: str, lang: str, theme_name: str, theme) -> str:
    from rich.console import Console

    console = Console(record=True, file=io.StringIO(), width=WIDTH, force_terminal=True, color_system="truecolor")
    for line in lines:
        console.print(line, crop=True, overflow="crop", no_wrap=True)
    svg = console.export_svg(title="sessionbridge", theme=theme, unique_id=f"{name}-{lang}-{theme_name}")
    if theme_name == "light":
        # Rich frames the window in translucent white, invisible on a white page.
        svg = svg.replace('stroke="rgba(255,255,255,0.35)"', 'stroke="#d0d7de"', 1)
    return "\n".join(line.rstrip() for line in svg.splitlines()) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/cli-reference.md is out of date")
    parser.add_argument("--no-images", action="store_true", help="only rewrite the command reference")
    options = parser.parse_args(argv)
    reference = cli_reference()
    if options.check:
        current = REFERENCE.read_text(encoding="utf-8") if REFERENCE.exists() else ""
        if current != reference:
            print("docs/cli-reference.md is out of date; run: python scripts/build_docs.py", file=sys.stderr)
            return 1
        print("docs/cli-reference.md is up to date")
        return 0
    REFERENCE.write_text(reference, encoding="utf-8", newline="\n")
    print(f"wrote {REFERENCE.relative_to(ROOT)}")
    if not options.no_images:
        for path in screenshots():
            print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
