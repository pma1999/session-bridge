class _Screen:
    """Records what the terminal shows: Rich output as it is printed, and each prompt as last drawn."""

    def __init__(self, console, source, keys):
        self.console, self.source, self.keys = console, source, list(keys)
        self.blocks: list[dict] = []
        self.apps: dict[int, dict] = {}

    def flush(self) -> None:
        printed = self.console.export_text(styles=True, clear=True)
        if printed:
            self.blocks.append({"kind": "text", "ansi": printed})

    def rendered(self, app, screen) -> None:
        from rich.text import Text

        block = self.apps.get(id(app))
        if block is None:
            self.flush()
            block = {"kind": "prompt", "erase": app.erase_when_done, "lines": []}
            self.apps[id(app)] = block
            self.blocks.append(block)
            # A prompt the scene has no keys for is interrupted (Ctrl+C), so a changed flow fails
            # instead of waiting forever for input.
            self.source.send_text(self.keys.pop(0) if self.keys else "\x03")
        if screen is None:
            return
        lines = []
        for y in range(screen.height):
            row = screen.data_buffer[y]
            line = Text()
            run, style = "", None
            for x in range(max(row.keys(), default=-1) + 1):
                cell = row[x]
                if cell.style != style and run:
                    line.append(run, _rich_style(style))
                    run = ""
                run, style = run + cell.char, cell.style
            if run:
                line.append(run, _rich_style(style))
            line.rstrip()
            lines.append(line)
        while lines and not lines[-1].plain.strip():
            lines.pop()
        block["lines"] = lines

    def frame(self, prompt: int, *, history: bool):
        """The terminal as it looked at prompt number ``prompt`` (0-based)."""
        from rich.text import Text

        prompts = [index for index, block in enumerate(self.blocks) if block["kind"] == "prompt"]
        end = prompts[prompt]
        start = end
        if history:
            while start > 0 and not (self.blocks[start - 1]["kind"] == "prompt" and self.blocks[start - 1]["erase"]):
                start -= 1
        lines = []
        for block in self.blocks[start : end + 1]:
            if block["kind"] == "text":
                lines += Text.from_ansi(block["ansi"].rstrip("\n")).split("\n")
            elif block is self.blocks[end] or not block["erase"]:
                lines += block["lines"]
        return lines


_STYLE_CACHE: dict[str, object] = {}


def _rich_style(style: str):
    """prompt_toolkit's class style for a cell, as the Rich style that draws the same."""
    from rich.style import Style

    if style not in _STYLE_CACHE:
        from session_bridge.interactive import STYLE

        attrs = STYLE.get_attrs_for_style_str(style)

        def colour(value):
            if not value or value == "default":
                return None
            if value.startswith("ansi"):
                name = value[4:]
                return "bright_" + name[6:] if name.startswith("bright") else name
            return "#" + value

        _STYLE_CACHE[style] = Style(
            color=colour(attrs.color),
            bgcolor=colour(attrs.bgcolor),
            bold=attrs.bold or None,
            italic=attrs.italic or None,
            underline=attrs.underline or None,
            reverse=attrs.reverse or None,
        )
    return _STYLE_CACHE[style]


@contextlib.contextmanager
def _capturing(keys):
    """Run the real screens on a fixed-size terminal fed with ``keys``, one string per prompt."""
    from prompt_toolkit.application import create_app_session
    from prompt_toolkit.data_structures import Size
    from prompt_toolkit.input import create_pipe_input
    from prompt_toolkit.output.vt100 import Vt100_Output
    from prompt_toolkit.renderer import Renderer
    from rich.console import Console

    from session_bridge import cli, interactive, ui

    console = Console(
        record=True,
        file=io.StringIO(),
        width=WIDTH,
        force_terminal=True,
        color_system="truecolor",
        markup=False,
        highlight=False,
    )
    original_render = Renderer.render
    saved = (cli._console_out, interactive._status, ui.datetime)
    with create_pipe_input() as source:
        recorder = _Screen(console, source, keys)

        def render(self, app, layout, is_done=False):
            original_render(self, app, layout, is_done)
            recorder.rendered(app, self._last_screen)

        output = Vt100_Output(io.StringIO(), lambda: Size(rows=HEIGHT, columns=WIDTH), term="xterm")
        Renderer.render = render
        cli._console_out = console
        interactive._status = lambda message: contextlib.nullcontext()
        ui.datetime = _FrozenClock
        try:
            with create_app_session(input=source, output=output):
                yield recorder
        finally:
            Renderer.render = original_render
            cli._console_out, interactive._status, ui.datetime = saved
            recorder.flush()


ESC, DOWN, ENTER = "\x1b", "\x1b[B", "\r"


def _scenes(data_dir: Path):
    """Each scene drives the start screen with keys and names the prompts worth a picture."""
    from session_bridge import installation, interactive, updates
    from session_bridge.releases import Release, Version

    bridge = _Bridge(data_dir)

    def browse():
        # Start screen → a session → Codex → the summary and its actions → back → leave.
        return interactive.run_home(bridge, cwd=FOLDER)

    class Offer:
        def result(self):
            return updates.Offer(
                current=Version(0, 8, 0),
                release=Release(
                    version=Version(0, 9, 0),
                    page_url="https://github.com/pma1999/session-bridge/releases/tag/v0.9.0",
                ),
                installation=installation.Installation(kind=installation.MANAGED),
            )

    def update():
        return interactive.run_home(bridge, cwd=FOLDER, update=Offer())

    return [
        (browse, [DOWN + ENTER, ENTER, ESC, ESC], {"home": (0, False), "convert": (2, True)}),
        (update, [ESC, ESC], {"update": (0, False)}),
    ]


