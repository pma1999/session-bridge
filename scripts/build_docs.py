def _text(value: str | None) -> str:
    """A help text as ``--help`` renders it: catalog keys become text, with their parameters filled."""
    from session_bridge import i18n
    from session_bridge.i18n import typer_chrome

    if not value:
        return ""
    return typer_chrome._text(value) if i18n.is_key(value) and i18n.has(value) else value


def _argument_name(param) -> str:
    """``KEY``, or ``[KEY]`` when it may be left out; a list of choices is shown as it is."""
    if param.metavar and not param.metavar.startswith("{"):
        return param.metavar
    name = param.human_readable_name.upper()
    return name if param.required else f"[{name}]"


def _usage(path: str, command) -> str:
    pieces = [path, "[OPTIONS]"]
    pieces += [_argument_name(param) for param in command.params if param.param_type_name == "argument"]
    if hasattr(command, "list_commands"):
        pieces.append("COMMAND [ARGS]...")
    return " ".join(pieces)


def _cell(value: str) -> str:
    return " ".join(value.split()).replace("|", "\\|")


def _anchor(path: str) -> str:
    return path.replace(" ", "-")


def _children(command, context) -> list[str]:
    """The visible subcommands of a group, in the order ``--help`` lists them; none for a command."""
    if not hasattr(command, "list_commands"):
        return []
    return [name for name in command.list_commands(context) if not command.get_command(context, name).hidden]


def _commands(command, path: str, parent=None):
    """Every visible command, depth first."""
    from typer._click import Context

    context = Context(command, info_name=path.split()[-1], parent=parent)
    yield path, command, context
    for name in _children(command, context):
        yield from _commands(command.get_command(context, name), f"{path} {name}", context)


def _option_row(param, context) -> tuple[str, str]:
    value = ""
    if not param.is_flag and not param.count:
        value = " " + {"str": "TEXT"}.get(param.type.name, param.type.name.upper())
    names = ", ".join(f"`{name}{value}`" for name in [*param.opts, *param.secondary_opts])
    notes = [_text(param.help)]
    if param.required:
        notes.append("Required.")
    if not param.is_flag and param.default not in (None, "", (), []) and not callable(param.default):
        notes.append(f"Default: `{param.default}`.")
    return names, " ".join(note for note in notes if note)


def cli_reference() -> str:
    import typer

    from session_bridge import cli

    with _language("en"):
        return _reference(typer.main.get_command(cli.app))


@contextlib.contextmanager
def _language(lang: str):
    """Use ``lang`` for a while, then the language that was in use before."""
    from session_bridge import i18n

    previous = (i18n.current(), i18n.source())
    i18n.use(lang)
    try:
        yield
    finally:
        i18n.use(previous[0], source=previous[1])


def _reference(root) -> str:
    entries = list(_commands(root, "sessionbridge"))
    lines = [
        "# Command reference",
        "",
        "<!-- Generated by scripts/build_docs.py from the command line itself. Do not edit by hand. -->",
        "",
        "Every command and option of `sessionbridge`, as `--help` shows them in English. "
        "`sessionbridge COMMAND --help` shows the same text in the language you use, and the "
        "[user guide](user-guide.md) explains how the commands fit together.",
        "",
        "`--json`, `--no-color` and `--lang`, listed under [`sessionbridge`](#sessionbridge), "
        "work with every command and anywhere on the line: `sessionbridge list --json`.",
        "",
        "## Commands",
        "",
    ]
    for path, command, _ in entries[1:]:
        summary = _cell(_text(command.help).split("\n\n")[0])
        lines.append(f"- [`{path}`](#{_anchor(path)}): {summary}")
    lines.append("")
    for path, command, context in entries:
        lines += [f"## {path}", "", _text(command.help).strip(), ""]
        lines += ["```text", _usage(path, command), "```", ""]
        arguments = [param for param in command.params if param.param_type_name == "argument"]
        options = [
            param
            for param in command.params
            if param.param_type_name == "option" and not param.hidden and "--help" not in param.opts
        ]
        if arguments:
            lines += ["| Argument | Description |", "| --- | --- |"]
            for param in arguments:
                lines.append(f"| `{_argument_name(param)}` | {_cell(_text(getattr(param, 'help', '')))} |")
            lines.append("")
        if options:
            lines += ["| Option | Description |", "| --- | --- |"]
            for param in options:
                names, description = _option_row(param, context)
                lines.append(f"| {names} | {_cell(description)} |")
            lines.append("")
        children = _children(command, context)
        if children:
            links = ", ".join(f"[`{name}`](#{_anchor(path + ' ' + name)})" for name in children)
            lines += [f"Commands: {links}.", ""]
    return "\n".join(lines).rstrip() + "\n"


