"""Generate the documentation that is derived from the program itself.

* ``docs/cli-reference.md`` from the command tree and the English catalog.
* ``docs/images/*.svg`` screenshots, drawn by the real interactive screens with made-up
  conversations. Nothing on this machine is read: sessions, links and the update offer are
  synthetic, and the data directory is a temporary one.

Usage::

    python scripts/build_docs.py            # rewrite both
    python scripts/build_docs.py --check    # fail when the command reference is out of date

Screenshots depend on the fonts of whoever views them, so only the reference is checked for drift.
"""

