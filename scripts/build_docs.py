class _FrozenClock(datetime):
    """``datetime`` whose ``now`` is fixed, so relative times read the same on every run."""

    @classmethod
    def now(cls, tz=None):
        return NOW if tz is None else NOW.astimezone(tz)


def _ago(**delta) -> str:
    return (NOW - timedelta(**delta)).isoformat()


